import { createGame } from '../js/core/state.js';
import { defaultDesign } from '../js/core/design.js';
import { autoPriceModel, canAutoPrice, variantPriceMul, variantCost, priceCurve, priceForecast } from '../js/core/pricing.js';
import { RAMS, STORAGES } from '../js/data/parts.js';
import { TECHS } from '../js/data/tech.js';

let bad = 0;
const check = (name, ok, detail = '') => { if (!ok) bad += 1; console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${detail ? '  ' + detail : ''}`); };
const s = createGame({ mode: 'sandbox', year: 2020, cash: 2e9 });
const design = defaultDesign(2020, TECHS.filter((t) => t.year <= 2020).map((t) => t.id));
const m = { id: 'm-price', name: '定价机', status: 'production', released: true, lineup: 'main', heat: 55, markets: ['cn', 'sea'], price: { cn: 1, sea: 1 }, design };
design.variants = [{ ram: design.parts.ram, stg: design.parts.storage }];
check('未任命销售负责人时不可一键定价', autoPriceModel(s, m).reason === 'no-head');
s.org.heads.sales = s.employees[0].id;
check('销售负责人可一键定价', canAutoPrice(s) === true);
const r = autoPriceModel(s, m);
check('覆盖全部已进入市场', r.ok && r.count === 2 && m.price.cn > 0 && m.price.sea > 0, JSON.stringify(m.price));
check('配置版本同步定价', design.variants[0].price?.cn > 0 && design.variants[0].price?.sea > 0, JSON.stringify(design.variants[0].price));
check('未进入市场不被写入', m.price.in === undefined);
const std = m.price.cn;
autoPriceModel(s, m, 'penetration');
check('渗透策略价格更低', m.price.cn < std, `${m.price.cn} < ${std}`);
autoPriceModel(s, m, 'premium');
check('溢价策略价格更高', m.price.cn > std, `${m.price.cn} > ${std}`);
const same = { ram: design.parts.ram, stg: design.parts.storage };
check('同配置版本系数为 1', variantPriceMul(m, same) === 1, String(variantPriceMul(m, same)));
const bigRam = RAMS[RAMS.length - 1];
const bigStg = STORAGES[STORAGES.length - 1];
const up = { ram: bigRam.id, stg: bigStg.id };
const upMul = variantPriceMul(m, up);
check('高配版本系数 > 1 且有上限', upMul > 1 && upMul <= 2.2, String(upMul));
check('高配版本成本更高', variantCost(s, m, up) >= variantCost(s, m, same), `${variantCost(s, m, up)} >= ${variantCost(s, m, same)}`);
design.variants[0].ram = bigRam.id;
design.variants[0].stg = bigStg.id;
autoPriceModel(s, m);
check('高配版本价格高于标配', design.variants[0].price.cn > m.price.cn, `${design.variants[0].price.cn} > ${m.price.cn}`);
// 价格—销量预测：5 档、价格递增、必有一个毛利最优；模拟不能污染当前定价
m.price.cn = std;
s.models.push(m);
m.heat = 70; m.inventory = 5000;
const curve = priceCurve(s, m, 'cn', 5, 0.3);
check('预测返回 5 档', curve.length === 5, String(curve.length));
check('预测价格递增', curve.every((r, i) => i === 0 || r.price > curve[i - 1].price), curve.map((r) => r.price).join(','));
check('预测含毛利最优', curve.filter((r) => r.best).length === 1, curve.map((r) => r.best).join(','));
check('预测不改变当前定价', m.price.cn === std, String(m.price.cn));
check('预测销量随价格下降', curve[curve.length - 1].units <= curve[0].units, `${curve[0].units} → ${curve[curve.length - 1].units}`);
const one = priceForecast(s, m, 'cn', std);
check('单点预测与曲线中心一致', one && one.price === std, JSON.stringify(one && { price: one.price, units: one.units }));
if (bad) process.exit(1);
console.log('\nPRICING PASS');
